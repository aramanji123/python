#Integer Variables
num1 = 10
num2 = 5

#Integer addition 
sum = num1 + num2
print(" Addition of num1 and num2: sum=",sum)
print("-------------------")

#Integer subtraction
Sub = num1 - num2
print(" subtraction of num1 and num2: sub=",Sub)
print("-------------------")


#Integer Multiplication 
Mul = num1 * num2
print(" Multiplication of num1 and num2: mul =",Mul)
print("-------------------")


#Integer Division
Div = num1 // num2
print(" Division of num1 and num2: Div =",Div)
print("-------------------")


#Integer Modulus(Reminder)
rem = num1 % num2
print(" Modulus of num1 and num2: rem =",rem)
print("-------------------")


#Absolute value
abs = abs(-10)
print(" absolute value: abs=",abs)


